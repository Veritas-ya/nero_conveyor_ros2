"""Protocols implemented by both simulated and physical device backends."""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from .types import (
    CommandReceipt,
    ConveyorState,
    DeviceHealth,
    GripperState,
    RGBDFrame,
    RobotState,
    SafetySignals,
    TrajectoryGoal,
)


@runtime_checkable
class RobotBackend(Protocol):
    @property
    def joint_names(self) -> tuple[str, ...]: ...

    def connect(self) -> None: ...

    def health(self) -> DeviceHealth: ...

    def read_state(self) -> RobotState: ...

    def enable(self) -> None: ...

    def disable(self) -> None: ...

    def submit_trajectory(self, goal: TrajectoryGoal) -> CommandReceipt: ...

    def cancel(self, goal_id: str | None = None) -> None: ...

    def hold(self) -> None: ...

    def close(self) -> None: ...


@runtime_checkable
class GripperBackend(Protocol):
    def connect(self) -> None: ...

    def health(self) -> DeviceHealth: ...

    def read_state(self) -> GripperState: ...

    def command_open_fraction(self, fraction: float) -> CommandReceipt: ...

    def hold(self) -> None: ...

    def close(self) -> None: ...


@runtime_checkable
class ConveyorBackend(Protocol):
    def connect(self) -> None: ...

    def health(self) -> DeviceHealth: ...

    def read_state(self) -> ConveyorState: ...

    def command_velocity(self, velocity_m_s: float) -> CommandReceipt: ...

    def stop(self) -> None: ...

    def close(self) -> None: ...


@runtime_checkable
class CameraBackend(Protocol):
    def start(self) -> None: ...

    def health(self) -> DeviceHealth: ...

    def read_latest(
        self, timeout_s: float = 0.0, *, after_sequence: int | None = None
    ) -> RGBDFrame: ...

    def stop(self) -> None: ...

    def close(self) -> None: ...


@runtime_checkable
class SafetyBackend(Protocol):
    def connect(self) -> None: ...

    def health(self) -> DeviceHealth: ...

    def read_state(self) -> SafetySignals: ...

    def close(self) -> None: ...
